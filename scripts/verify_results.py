#!/usr/bin/env python3
"""Rebuild every recorded solution and validate raw experiment results."""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

try:
    from .experiment_common import (
        RAW_FIELDS,
        calculate_gap,
        decode_int_sequence,
        parse_bool,
        parse_optional_float,
        read_csv_rows,
    )
except ImportError:  # Direct execution
    from experiment_common import (  # type: ignore[no-redef]
        RAW_FIELDS,
        calculate_gap,
        decode_int_sequence,
        parse_bool,
        parse_optional_float,
        read_csv_rows,
    )

from tpp.domain.evaluation import build_solution  # noqa: E402
from tpp.io import load_instance  # noqa: E402


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Validate raw TPP experiment CSV rows.")
    parser.add_argument("results", help="raw_results.csv generated by run_benchmarks.py")
    parser.add_argument("--report", help="optional JSON verification report")
    parser.add_argument("--tolerance", type=float, default=1e-8)
    return parser


def _assert_close(actual: float, expected: float, name: str, tolerance: float) -> None:
    if not math.isclose(actual, expected, rel_tol=0.0, abs_tol=tolerance):
        raise ValueError(f"{name} mismatch: recorded={actual:g}, rebuilt={expected:g}")


def _verify_row(
    row: dict[str, str],
    cache: dict[str, object],
    tolerance: float,
) -> None:
    if not parse_bool(row.get("feasible"), "feasible"):
        raise ValueError(f"run was recorded as infeasible: {row.get('error') or 'unknown error'}")
    if row.get("error", "").strip():
        raise ValueError("a feasible row must not contain an error message")

    source = row["source"]
    if source not in cache:
        cache[source] = load_instance(source)
    instance = cache[source]
    if instance.name != row["instance"]:  # type: ignore[attr-defined]
        raise ValueError("instance name does not match the referenced JSON file")
    if instance.market_count != int(row["market_count"]):  # type: ignore[attr-defined]
        raise ValueError("market_count does not match the referenced JSON file")
    if instance.item_count != int(row["item_count"]):  # type: ignore[attr-defined]
        raise ValueError("item_count does not match the referenced JSON file")

    route = decode_int_sequence(row["route"], "route")
    item_markets = decode_int_sequence(row["item_markets"], "item_markets")
    rebuilt = build_solution(instance, route)  # type: ignore[arg-type]
    if rebuilt.item_markets != item_markets:
        raise ValueError("item_markets does not match the cheapest assignment for the route")

    travel_cost = parse_optional_float(row["travel_cost"], "travel_cost")
    purchase_cost = parse_optional_float(row["purchase_cost"], "purchase_cost")
    total_cost = parse_optional_float(row["total_cost"], "total_cost")
    if travel_cost is None or purchase_cost is None or total_cost is None:
        raise ValueError("a feasible row must contain all cost fields")
    _assert_close(travel_cost, rebuilt.travel_cost, "travel_cost", tolerance)
    _assert_close(purchase_cost, rebuilt.purchase_cost, "purchase_cost", tolerance)
    _assert_close(total_cost, rebuilt.total_cost, "total_cost", tolerance)

    reference = parse_optional_float(row["best_known_cost"], "best_known_cost")
    if reference is not None and reference <= 0:
        raise ValueError("best_known_cost must be greater than zero")
    recorded_gap = parse_optional_float(row["gap_percent"], "gap_percent")
    expected_gap = calculate_gap(rebuilt.total_cost, reference)
    if expected_gap is None:
        if recorded_gap is not None:
            raise ValueError("gap_percent is present without a best_known_cost")
    else:
        if recorded_gap is None:
            raise ValueError("gap_percent is missing despite a best_known_cost")
        _assert_close(recorded_gap, expected_gap, "gap_percent", tolerance)
        if recorded_gap < -tolerance:
            raise ValueError("solution cost is lower than the claimed best-known cost")

    if int(row["iterations"]) < 0:
        raise ValueError("iterations must be non-negative")
    if int(row["perturbations"]) < 0 or int(row["diversity_restarts"]) < 0:
        raise ValueError("search counters must be non-negative")
    elapsed = parse_optional_float(row["elapsed_seconds"], "elapsed_seconds")
    if elapsed is None or elapsed < 0:
        raise ValueError("elapsed_seconds must be non-negative")


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.tolerance <= 0:
            raise ValueError("tolerance must be greater than zero.")
        rows = read_csv_rows(args.results, RAW_FIELDS)
        if not rows:
            raise ValueError("Raw results CSV contains no runs.")

        cache: dict[str, object] = {}
        seen: set[tuple[str, ...]] = set()
        errors: list[str] = []
        for index, row in enumerate(rows, start=2):
            key = tuple(
                row[field]
                for field in (
                    "source",
                    "algorithm",
                    "seed",
                    "k_max",
                    "lambda_max",
                    "delta_add",
                    "delta_drop",
                    "delta_exchange",
                    "alpha",
                )
            )
            if key in seen:
                errors.append(f"line {index}: duplicate experiment run")
                continue
            seen.add(key)
            try:
                _verify_row(row, cache, args.tolerance)
            except (OSError, TypeError, ValueError) as exc:
                errors.append(f"line {index}: {exc}")

        for error in errors:
            print(error, file=sys.stderr)
        report = {
            "results": str(Path(args.results).resolve()),
            "rows": len(rows),
            "valid_rows": len(rows) - len(errors),
            "invalid_rows": len(errors),
            "status": "PASS" if not errors else "FAIL",
        }
        if args.report:
            destination = Path(args.report)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(
                json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
            )
        print(
            f"rows={report['rows']} valid={report['valid_rows']} "
            f"invalid={report['invalid_rows']} verification_status={report['status']}"
        )
        return 1 if errors else 0
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
