#!/usr/bin/env python3
"""Generate dependency-free SVG figures from raw TPP experiment results."""

from __future__ import annotations

import argparse
import math
import sys
from collections import defaultdict
from html import escape
from pathlib import Path
from typing import Mapping, Sequence

try:
    from .experiment_common import (
        RAW_FIELDS,
        parse_bool,
        read_csv_rows,
        summarize_records,
    )
except ImportError:  # Direct execution
    from experiment_common import (  # type: ignore[no-redef]
        RAW_FIELDS,
        parse_bool,
        read_csv_rows,
        summarize_records,
    )


COLORS = ("#2563eb", "#f97316", "#16a34a", "#9333ea", "#dc2626", "#0891b2")


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Plot TPP experiment CSV as SVG figures.")
    parser.add_argument("results", help="raw_results.csv generated by run_benchmarks.py")
    parser.add_argument("--output-dir", default="tmp/experiments/figures")
    return parser


def _config_key(row: Mapping[str, str]) -> tuple[str, ...]:
    return tuple(
        row.get(field, "")
        for field in (
            "algorithm",
            "k_max",
            "lambda_max",
            "delta_add",
            "delta_drop",
            "delta_exchange",
            "alpha",
        )
    )


def _series_labels(rows: Sequence[Mapping[str, str]]) -> dict[tuple[str, ...], str]:
    keys = sorted({_config_key(row) for row in rows})
    algorithm_counts: dict[str, int] = defaultdict(int)
    for key in keys:
        algorithm_counts[key[0]] += 1
    labels: dict[tuple[str, ...], str] = {}
    for key in keys:
        if algorithm_counts[key[0]] == 1:
            labels[key] = key[0]
        else:
            labels[key] = f"{key[0]} (k={key[1]}, lambda={key[2]}, alpha={key[6]})"
    return labels


def _nice_ceiling(value: float) -> float:
    if value <= 0:
        return 1.0
    exponent = math.floor(math.log10(value))
    magnitude = 10**exponent
    normalized = value / magnitude
    step = 1 if normalized <= 1 else 2 if normalized <= 2 else 5 if normalized <= 5 else 10
    return step * magnitude


def _svg_document(width: int, height: int, body: Sequence[str]) -> str:
    return "\n".join(
        (
            '<?xml version="1.0" encoding="UTF-8"?>',
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}">',
            '<rect width="100%" height="100%" fill="#ffffff"/>',
            '<style>text{font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif;}'
            '.axis{fill:#475569;font-size:12px}.title{fill:#0f172a;font-size:20px;font-weight:700}'
            '.legend{fill:#334155;font-size:12px}</style>',
            *body,
            "</svg>",
            "",
        )
    )


def _write_grouped_bars(
    path: Path,
    summaries: Sequence[Mapping[str, str]],
    *,
    metric: str,
    title: str,
    y_label: str,
) -> bool:
    usable = [row for row in summaries if row.get(metric, "").strip()]
    if not usable:
        return False
    categories = sorted({row["instance"] for row in usable})
    labels = _series_labels(usable)
    series = sorted(labels)
    values = {
        (row["instance"], _config_key(row)): float(row[metric])
        for row in usable
    }
    maximum = _nice_ceiling(max(values.values()) * 1.08)

    width = max(840, 190 + len(categories) * max(90, 34 * len(series)))
    height = 540
    left, right, top, bottom = 90, 40, 85, 140
    plot_width = width - left - right
    plot_height = height - top - bottom
    group_width = plot_width / len(categories)
    bar_width = min(28.0, group_width * 0.72 / max(1, len(series)))
    body = [f'<text class="title" x="{left}" y="34">{escape(title)}</text>']

    for tick in range(6):
        value = maximum * tick / 5
        y = top + plot_height - plot_height * tick / 5
        body.append(
            f'<line x1="{left}" y1="{y:.2f}" x2="{width-right}" y2="{y:.2f}" '
            'stroke="#e2e8f0" stroke-width="1"/>'
        )
        body.append(
            f'<text class="axis" x="{left-10}" y="{y+4:.2f}" text-anchor="end">'
            f"{value:.3g}</text>"
        )

    for category_index, category in enumerate(categories):
        center = left + group_width * (category_index + 0.5)
        total_width = bar_width * len(series)
        for series_index, key in enumerate(series):
            value = values.get((category, key))
            if value is None:
                continue
            x = center - total_width / 2 + series_index * bar_width
            bar_height = 0 if maximum == 0 else plot_height * value / maximum
            y = top + plot_height - bar_height
            body.append(
                f'<rect x="{x:.2f}" y="{y:.2f}" width="{max(2, bar_width-3):.2f}" '
                f'height="{bar_height:.2f}" rx="2" fill="{COLORS[series_index % len(COLORS)]}">'
                f"<title>{escape(labels[key])}: {value:.6g}</title></rect>"
            )
        body.append(
            f'<text class="axis" transform="translate({center+5:.2f},{top+plot_height+18}) '
            f'rotate(30)" text-anchor="start">{escape(category)}</text>'
        )

    body.append(
        f'<line x1="{left}" y1="{top+plot_height}" x2="{width-right}" '
        f'y2="{top+plot_height}" stroke="#64748b"/>'
    )
    body.append(
        f'<text class="axis" transform="translate(22,{top+plot_height/2}) rotate(-90)" '
        f'text-anchor="middle">{escape(y_label)}</text>'
    )
    legend_x = left
    for index, key in enumerate(series):
        x = legend_x + index * max(150, (width - left - right) / max(1, len(series)))
        body.append(
            f'<rect x="{x:.2f}" y="52" width="13" height="13" rx="2" '
            f'fill="{COLORS[index % len(COLORS)]}"/>'
        )
        body.append(
            f'<text class="legend" x="{x+19:.2f}" y="63">{escape(labels[key])}</text>'
        )

    path.write_text(_svg_document(width, height, body), encoding="utf-8")
    return True


def _percentile(values: Sequence[float], probability: float) -> float:
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    position = (len(ordered) - 1) * probability
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return ordered[lower]
    fraction = position - lower
    return ordered[lower] * (1 - fraction) + ordered[upper] * fraction


def _write_stability_boxplot(path: Path, rows: Sequence[Mapping[str, str]]) -> bool:
    feasible = [
        row
        for row in rows
        if parse_bool(row.get("feasible"), "feasible") and row.get("total_cost", "").strip()
    ]
    if not feasible:
        return False
    labels = _series_labels(feasible)
    grouped: dict[tuple[str, tuple[str, ...]], list[float]] = defaultdict(list)
    for row in feasible:
        grouped[(row["instance"], _config_key(row))].append(float(row["total_cost"]))
    groups = sorted(grouped)
    all_values = [value for values in grouped.values() for value in values]
    minimum = min(all_values)
    maximum = max(all_values)
    span = maximum - minimum
    padding = max(1.0, span * 0.08, maximum * 0.01)
    y_min = max(0.0, minimum - padding)
    y_max = maximum + padding

    width = max(860, 180 + len(groups) * 100)
    height = 560
    left, right, top, bottom = 90, 40, 70, 155
    plot_width = width - left - right
    plot_height = height - top - bottom

    def y_position(value: float) -> float:
        return top + plot_height * (y_max - value) / (y_max - y_min)

    body = [
        f'<text class="title" x="{left}" y="34">Seed stability: total cost distribution</text>'
    ]
    for tick in range(6):
        value = y_min + (y_max - y_min) * tick / 5
        y = y_position(value)
        body.append(
            f'<line x1="{left}" y1="{y:.2f}" x2="{width-right}" y2="{y:.2f}" '
            'stroke="#e2e8f0"/>'
        )
        body.append(
            f'<text class="axis" x="{left-10}" y="{y+4:.2f}" text-anchor="end">'
            f"{value:.4g}</text>"
        )

    spacing = plot_width / len(groups)
    series_order = sorted(labels)
    for index, group in enumerate(groups):
        instance, key = group
        values = grouped[group]
        low = min(values)
        q1 = _percentile(values, 0.25)
        median = _percentile(values, 0.5)
        q3 = _percentile(values, 0.75)
        high = max(values)
        x = left + spacing * (index + 0.5)
        color = COLORS[series_order.index(key) % len(COLORS)]
        body.append(
            f'<line x1="{x:.2f}" y1="{y_position(high):.2f}" x2="{x:.2f}" '
            f'y2="{y_position(low):.2f}" stroke="{color}" stroke-width="2"/>'
        )
        body.append(
            f'<line x1="{x-12:.2f}" y1="{y_position(high):.2f}" x2="{x+12:.2f}" '
            f'y2="{y_position(high):.2f}" stroke="{color}" stroke-width="2"/>'
        )
        body.append(
            f'<line x1="{x-12:.2f}" y1="{y_position(low):.2f}" x2="{x+12:.2f}" '
            f'y2="{y_position(low):.2f}" stroke="{color}" stroke-width="2"/>'
        )
        box_y = y_position(q3)
        box_height = max(1.5, y_position(q1) - box_y)
        body.append(
            f'<rect x="{x-20:.2f}" y="{box_y:.2f}" width="40" height="{box_height:.2f}" '
            f'fill="{color}" fill-opacity="0.22" stroke="{color}" stroke-width="2">'
            f"<title>n={len(values)}, min={low:.6g}, median={median:.6g}, max={high:.6g}</title>"
            "</rect>"
        )
        body.append(
            f'<line x1="{x-20:.2f}" y1="{y_position(median):.2f}" x2="{x+20:.2f}" '
            f'y2="{y_position(median):.2f}" stroke="{color}" stroke-width="3"/>'
        )
        group_label = f"{instance} / {labels[key]}"
        body.append(
            f'<text class="axis" transform="translate({x+4:.2f},{top+plot_height+18}) rotate(35)" '
            f'text-anchor="start">{escape(group_label)}</text>'
        )

    body.append(
        f'<text class="axis" transform="translate(22,{top+plot_height/2}) rotate(-90)" '
        'text-anchor="middle">Total cost (lower is better)</text>'
    )
    path.write_text(_svg_document(width, height, body), encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        rows = read_csv_rows(args.results, RAW_FIELDS)
        if not rows:
            raise ValueError("Raw results CSV contains no runs.")
        summaries = summarize_records(rows)
        destination = Path(args.output_dir)
        destination.mkdir(parents=True, exist_ok=True)

        generated: list[Path] = []
        charts = (
            (
                "mean_cost_comparison.svg",
                "mean_cost",
                "Mean solution cost by instance",
                "Mean total cost (lower is better)",
            ),
            (
                "gap_comparison.svg",
                "mean_gap_percent",
                "Mean optimality gap by instance",
                "Mean gap (%)",
            ),
            (
                "runtime_comparison.svg",
                "mean_elapsed_seconds",
                "Mean CPU runtime by instance",
                "Mean elapsed seconds",
            ),
        )
        for filename, metric, title, y_label in charts:
            path = destination / filename
            if _write_grouped_bars(
                path, summaries, metric=metric, title=title, y_label=y_label
            ):
                generated.append(path)
        stability = destination / "seed_stability.svg"
        if _write_stability_boxplot(stability, rows):
            generated.append(stability)
        if not generated:
            raise ValueError("No feasible numeric results were available to plot.")
        for path in generated:
            print(f"figure={path}")
        return 0
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
