#!/usr/bin/env python3
"""Create instance-level and algorithm-level CSV summaries from raw runs."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    from .experiment_common import (
        ALGORITHM_SUMMARY_FIELDS,
        RAW_FIELDS,
        SUMMARY_FIELDS,
        read_csv_rows,
        summarize_algorithms,
        summarize_records,
        write_csv_rows,
    )
except ImportError:  # Direct execution
    from experiment_common import (  # type: ignore[no-redef]
        ALGORITHM_SUMMARY_FIELDS,
        RAW_FIELDS,
        SUMMARY_FIELDS,
        read_csv_rows,
        summarize_algorithms,
        summarize_records,
        write_csv_rows,
    )


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Summarize raw TPP experiment runs.")
    parser.add_argument("results", help="raw_results.csv generated by run_benchmarks.py")
    parser.add_argument("--output", default="tmp/experiments/summary.csv")
    parser.add_argument(
        "--algorithm-output", default="tmp/experiments/algorithm_summary.csv"
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        rows = read_csv_rows(args.results, RAW_FIELDS)
        if not rows:
            raise ValueError("Raw results CSV contains no runs.")
        summaries = summarize_records(rows)
        algorithm_summaries = summarize_algorithms(rows)
        write_csv_rows(args.output, SUMMARY_FIELDS, summaries)
        write_csv_rows(
            args.algorithm_output,
            ALGORITHM_SUMMARY_FIELDS,
            algorithm_summaries,
        )
        print(
            f"instance_summary={Path(args.output)} rows={len(summaries)}\n"
            f"algorithm_summary={Path(args.algorithm_output)} rows={len(algorithm_summaries)}"
        )
        return 0
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
